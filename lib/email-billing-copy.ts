/** Busca uma string de billing; fallback 'en'. Nunca lança. */
export function billingEmailCopy(locale: Locale, key: BillingEmailCopyKey): string {
    const dict = BILLING_EMAIL_COPY[locale] ?? BILLING_EMAIL_COPY['en'];
    return dict[key] ?? BILLING_EMAIL_COPY['en'][key] ?? key;
}

/** Interpola `{var}` sem lançar se faltar valor (some, e o usuário lê o resto). */
export function interpolateBilling(template: string, vars: Record<string, string | number | null | undefined>): string {
    return template.replace(/\{([a-zA-Z_][a-zA-Z0-9_]*)\}/g, (_, k: string) => {
        const v = vars[k];
        if (v === null || v === undefined) return '';
        return String(v);
    });
}
